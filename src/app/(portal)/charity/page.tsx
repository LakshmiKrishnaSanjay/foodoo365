import Link from "next/link";
import { Suspense } from "react";
import { CompareBars, CountBars } from "@/components/portal/charts";
import { EmptyState, PageIntro, PageSkeleton, Panel, StatusPill } from "@/components/portal/bits";
import { FilterBar } from "@/components/portal/filters";
import { Button } from "@/components/ui/button";
import { getCharity, preservedQuery } from "@/lib/data/queries";
import { readRequest } from "@/lib/portal-request";

export const metadata = { title: "Charity Impact" };

export default function Page(props: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  return <Suspense fallback={<PageSkeleton />}><CharityPage searchParams={props.searchParams} /></Suspense>;
}

async function CharityPage({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const { session, filters, choices } = await readRequest(searchParams);
  const data = await getCharity(session.id, filters);
  if (!data) return null;
  const query = preservedQuery(filters);
  return (
    <div className="space-y-6">
      <PageIntro title="Charity impact" description="The same sales fund charity and investor profit. Twenty percent of eligible sales is allocated to charity meals. After that allocation, food cost, operating costs and reserves, what remains is distributable profit, and your agreement takes a share of it." />
      <Suspense><FilterBar trucks={choices.trucks} truck={filters.truck} /></Suspense>
      <Panel title="Charity and profit from the same sale" description="A meal with ₹20 of eligible sales allocates ₹4 to charity. The other ₹16 stays with the truck. After the cost of the meal and the truck's operating costs, what is left is profit. On the Chicken Shawarma Meal, ₹22 of eligible sales allocates ₹4.40 to charity, and the rest is available for costs and profit.">
        <p className="text-sm leading-6 text-muted-foreground">Your charity figure is your contractual entitlement percentage of the 20% allocation on trucks you are invested in. It attributes the allocation. It is not a count of people fed, and it does not identify a beneficiary. Your earnings are a separate share of distributable profit, not a share of the meal price.</p>
      </Panel>
      <Panel title="Profit taken from these sales" description="Charity is set aside first. Profit is what remains after charity and the costs of running the trucks. A loss does not create a payout." action={<Button asChild variant="outline" className="h-10"><Link href={`/profit${query}`}>Open profit and earnings</Link></Button>}>
        <dl className="grid gap-3 sm:grid-cols-2 xl:grid-cols-3">
          {[
            ["Eligible sales", data.eligible.formatted],
            ["Charity allocation (20%)", data.allocated.formatted],
            ["Food, operating and other costs", data.costs.formatted],
            ["Reserves", data.reserves.formatted],
            ["Distributable profit", data.distributable.formatted],
            ["Your earnings", data.earnings.formatted],
          ].map(([label, value]) => (
            <div key={label}>
              <dt className="text-xs tracking-wide text-muted-foreground uppercase">{label}</dt>
              <dd className="mt-1 font-heading text-2xl tabular-nums">{value}</dd>
            </div>
          ))}
        </dl>
      </Panel>
      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        {[
          ["Total eligible sales", data.eligible.formatted],
          ["Charity funds allocated", data.allocated.formatted],
          ["Charity funds used", data.used.formatted],
          ["Remaining charity balance", data.remaining.formatted],
          ["Meals sponsored", data.sponsored.toLocaleString("en-AE")],
          ["Meals prepared", data.prepared.toLocaleString("en-AE")],
          ["Meals distributed", data.distributed.toLocaleString("en-AE")],
          ["Average cost per charity meal", data.average?.formatted ?? "—"],
        ].map(([label, value]) => (
          <div key={label} className="rounded-xl bg-card p-4 ring-1 ring-foreground/10">
            <p className="text-xs tracking-wide text-muted-foreground uppercase">{label}</p>
            <p className="mt-2 font-heading text-2xl tabular-nums">{value}</p>
          </div>
        ))}
      </div>
      <Panel title="Your attributable contribution" description={data.attributed.formatted}>
        <p className="text-sm leading-6">This applies your entitlement percentage to allocations generated by your trucks during the selected dates. Company-retained allocation and other investors&apos; agreements are not itemised.</p>
      </Panel>
      <div className="grid gap-4 xl:grid-cols-2">
        <Panel title="Charity contribution trend"><CompareBars data={data.months} xKey="label" bars={[{ key: "allocated", name: "Allocated", color: "var(--primary)" }, { key: "used", name: "Used", color: "var(--gold)" }]} /></Panel>
        <Panel title="Meals distributed"><CountBars data={data.months} bars={[{ key: "distributed", name: "Distributed meals", color: "var(--positive)" }]} /></Panel>
      </div>
      <Panel title="Impact history" description="Sponsored means funds or meals are committed. Prepared means meals are ready. Distributed means meals have gone out. None of these statuses is a named beneficiary.">
        {data.history.length === 0 ? <EmptyState title="No charity records" body="No utilization was recorded for these trucks and dates." /> : (
          <ul className="divide-y divide-border">
            {data.history.map((row) => (
              <li key={row.id} className="grid gap-2 py-3 text-sm md:grid-cols-[8rem_1fr_auto] md:items-center">
                <span className="text-muted-foreground">{row.date}</span>
                <span>
                  <span className="font-medium">{row.truck}</span>
                  <span className="mt-1 block text-muted-foreground">{row.meals} meals · {row.reference}. {row.note}</span>
                </span>
                <span className="flex items-center gap-3 md:justify-end"><StatusPill status={row.status} /><span className="tabular-nums">{row.amount.formatted}</span></span>
              </li>
            ))}
          </ul>
        )}
      </Panel>
    </div>
  );
}
